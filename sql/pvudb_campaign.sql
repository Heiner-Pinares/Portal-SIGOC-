SELECT
PLAN, 
DSC_PLAN, 
CAMPANA, 
DSC_CAMPANA, 
FEC_INI_CAMPANA, 
FEC_FIN_CAMPANA, 
DSC_SOLUCION, 
TMCODE, SPCODE, SNCODE,
SERVICIO, 
DSC_SERVICIO,
--PLAN||'|'||CAMPANA||'|'||SNCODE LLAVE,
 CF_SIN_IGV,
  CF_CON_IGV, 
  --TIPO_SERVICIO, 
  DSC_TIPO_SERVICIO,
PLAN||'-'||CAMPANA||'-'||SNCODE LLAVE
FROM
(SELECT CA.CAMPV_CODIGO AS CAMPANA,
       CA.CAMPV_DESCRIPCION AS DSC_CAMPANA,
       CA.MODALIDAD_VENTA AS MODALIDAD_CAMPANA,
       CA.CAMPV_FLUJO AS FLUJO_CAMPANA,
       CA.CAMPV_TIPO_OPERACION AS OPERACION_CAMPANA,
       CA.TOFC_CODIGO AS OFERTA_CAMPANA,
       CA.CAMPD_FECHA_INICIO AS FEC_INI_CAMPANA,
       CA.CAMPD_FECHA_FIN AS FEC_FIN_CAMPANA,
       AP.PAQTV_CODIGO AS SOLUCION,
       AP.PAQTV_DESCRIPCION AS DSC_SOLUCION,
       PL.PLNV_CODIGO AS PLAN,
       PL.PLNV_DESCRIPCION AS DSC_PLAN,
       PL.PLNV_TIPO_FLUJO2 AS FLUJO_PLAN,
       PL.TPROC_CODIGO AS OFERTA_PLAN,
       (SELECT LISTAGG(SAPO.TOPEN_CODIGO, '|') WITHIN GROUP(ORDER BY SAPO.TOPEN_CODIGO ASC)
          FROM USRPVU.SISACT_AP_PLAN_OPERACION SAPO
         WHERE SAPO.PLNV_CODIGO = PL.PLNV_CODIGO
           AND SAPO.PRDC_CODIGO = PL.PLNC_TIPO_PRODUCTO) AS OPERACION_PLAN,
       (SELECT LISTAGG(SAPD.DOCC_CODIGO, '|') WITHIN GROUP(ORDER BY SAPD.DOCC_CODIGO ASC)
          FROM USRPVU.SISACT_AP_PLAN_DOC SAPD
         WHERE SAPD.PLANC_CODIGO = PL.PLNV_CODIGO
           AND SAPD.PRDC_CODIGO = PL.PLNC_TIPO_PRODUCTO) AS DOCUMENTO_PLAN,
       (SELECT LISTAGG(SAPA.PLZAC_CODIGO, '|') WITHIN GROUP(ORDER BY SAPA.PLZAC_CODIGO ASC)
          FROM USRPVU.SISACT_AP_PLAN_ACUERDO SAPA
         WHERE SAPA.PLNV_CODIGO = PL.PLNV_CODIGO) AS PLAZO_PLAN,
       (SELECT LISTAGG(SAPB.PRCLN_CODIGO, '|') WITHIN GROUP(ORDER BY SAPB.PRCLN_CODIGO ASC)
          FROM USRPVU.SISACT_AP_PLAN_BILLETERA SAPB
         WHERE SAPB.PLNV_CODIGO = PL.PLNV_CODIGO
           AND SAPB.PRDC_CODIGO = PL.PLNC_TIPO_PRODUCTO) AS BILLETERA_PLAN,
       '' AS MAX_SECUENCIAL,
       '' AS SECUENCIAL,
       PL.PLNV_CODIGO_BSCS AS TMCODE,
       CS.SPCODE AS SPCODE,
       CS.SNCODE AS SNCODE,
       '' AS ACCION,
       '' AS DSC_PROMOCION,
       '' AS SPCODE_SHDES,
       '' AS DESCUENTO,
       '' AS PERIODO,
       '' AS TIPO_DESCUENTO,
       '' AS MOTIVO,
       '' AS FEC_INI_PROMOCION,
       '' AS FEC_FIN_PROMOCION,
       S.SERVV_CODIGO AS SERVICIO,
       S.SERVV_DESCRIPCION AS DSC_SERVICIO,
       PS.PSRVN_CARGO_FIJO AS CF_SIN_IGV,
       TO_CHAR(ROUND(PS.PSRVN_CARGO_FIJO * 1.18, 2), 'FM99990.00') AS CF_CON_IGV,
       '' AS BONO,
       '' AS IPTV,
       S.SERVV_CODIGO_EXT AS CODIGO_EXTERNO,
       S.SERVV_DES_EXT AS DSC_CODIGO_EXTERNO,
       S.SERVV_CAPACIDAD AS CAPACIDAD,
       S.SERVV_UNIDAD_CAPC AS UNIDAD,
       S.SERVI_CO_SER AS CO_SER,
       SE.IDEQUIPO AS EQUIPO,
       SE.EQUIPO AS DSC_EQUIPO,
       SE.CANT_EQUIPO AS CANT_EQUIPO,
       TO_CHAR(SM.MATV_ID_SAP) AS CODTIPEQU,
       SM.TIPEQU AS TIPEQU,
       SM.MATV_DES_SAP AS DSC_EQUIPO_SGA,
       TO_CHAR(SATM.TMATC_CODIGO) AS TIPO_EQUIPO,
       SATM.TMATV_DESCRIPCION AS DSC_TIPO_EQUIPO,
       SM.MATV_TIPO_MATERIAL AS CATEGORIA_EQUIPO,
       SI.ITEMN_DESCRIPCION AS DSC_GRUPO_EQUIPO,
       G.GSRVC_CODIGO AS GRUPO_SERVICIO,
       G.GSRVV_DESCRIPCION AS DSC_GRUPO_SERVICIO,
       G.GSRVC_PRINCIPAL AS GRUPO_PRINCIPAL,
       TO_CHAR(G.GSRVC_PADRE) AS GRUPO_PADRE,
       PS.PSRVV_SELECCIONABLE AS SELECCIONABLE,
       PS.PSRVC_FLG_DEFECTO AS DEFECTO,
       CASE
         WHEN G.GSRVC_PRINCIPAL = '1' THEN
          '1'
         WHEN PS.PSRVV_SELECCIONABLE = '1' AND PS.PSRVC_FLG_DEFECTO = '0' THEN
          '2'
         WHEN G.GSRVC_CODIGO NOT IN ('8', '15') AND
              PS.PSRVV_SELECCIONABLE = '0' AND PS.PSRVC_FLG_DEFECTO = '0' THEN
          '3'
         WHEN G.GSRVC_CODIGO IN ('8', '15') AND PS.PSRVV_SELECCIONABLE = '0' AND
              PS.PSRVC_FLG_DEFECTO = '0' THEN
          '4'
       END TIPO_SERVICIO,
       CASE
         WHEN G.GSRVC_PRINCIPAL = '1' THEN
          'CORE'
         WHEN PS.PSRVV_SELECCIONABLE = '1' AND PS.PSRVC_FLG_DEFECTO = '0' THEN
          'CORE ADICIONAL'
         WHEN G.GSRVC_CODIGO NOT IN ('8', '15') AND
              PS.PSRVV_SELECCIONABLE = '0' AND PS.PSRVC_FLG_DEFECTO = '0' THEN
          'ADICIONAL'
         WHEN G.GSRVC_CODIGO IN ('8', '15') AND PS.PSRVV_SELECCIONABLE = '0' AND
              PS.PSRVC_FLG_DEFECTO = '0' THEN
          'EQUIPO ALQUILER'
       END DSC_TIPO_SERVICIO,
       '' AS APLICA_FC,
       '' AS APLICA_PLAYA,
       '' AS FAMILIA
  FROM USRPVU.SISACT_AP_PLAN PL
  LEFT JOIN USRPVU.SISACT_AP_CAMPANA_PLAN CAC
    ON CAC.PLNV_CODIGO = PL.PLNV_CODIGO
   AND CAC.PRDC_CODIGO = PL.PLNC_TIPO_PRODUCTO
  LEFT JOIN USRPVU.SISACT_AP_CAMPANA CA
    ON CA.CAMPV_CODIGO = CAC.CAMPV_CODIGO
   AND CA.CAMPV_TIPO_PRODUCTO = CAC.PRDC_CODIGO
 INNER JOIN USRPVU.SISACT_AP_PLAN_SERV PS
    ON PS.PLNV_CODIGO = PL.PLNV_CODIGO
   AND PS.PRDC_CODIGO = PL.PLNC_TIPO_PRODUCTO
 INNER JOIN USRPVU.SISACT_CONFIG_SERVICIO CS
    ON CS.PLNV_CODIGO = PL.PLNV_CODIGO
   AND CS.PRDC_CODIGO = PL.PLNC_TIPO_PRODUCTO
   AND CS.TMCODE = PL.PLNV_CODIGO_BSCS
 INNER JOIN USRPVU.SISACT_AP_SERVICIO S
    ON S.SERVV_CODIGO = PS.SERVV_CODIGO
   AND S.SERVV_SPCODE = PS.SPCODE
   AND S.PRDC_CODIGO = PS.PRDC_CODIGO
   AND S.SERVV_CODIGO = CS.SERVV_CODIGO
   AND S.SERVV_ID_BSCS = CS.SNCODE
   AND S.SERVV_SPCODE = CS.SPCODE
   AND S.PRDC_CODIGO = CS.PRDC_CODIGO
 INNER JOIN USRPVU.SISACT_AP_GRUPO_SERVICIO G
    ON G.GSRVC_CODIGO = S.GSRVC_CODIGO
   AND G.PRDC_CODIGO = S.PRDC_CODIGO
 INNER JOIN USRPVU.SISACT_AP_PAQUETE_PLAN PP
    ON PP.PLNV_CODIGO = PL.PLNV_CODIGO
   AND PP.PRDC_CODIGO = PL.PLNC_TIPO_PRODUCTO
 INNER JOIN USRPVU.SISACT_AP_PAQUETE AP
    ON AP.PAQTV_CODIGO = PP.PAQTV_CODIGO
   AND AP.PRDC_CODIGO = PP.PRDC_CODIGO
  LEFT JOIN USRPVU.SISACT_AP_SERVICIO_EQUIPO SE
    ON SE.IDSERVICIO = S.SERVV_CODIGO
   AND SE.COD_GRUPO = S.GSRVC_CODIGO
  LEFT JOIN USRPVU.SISACT_AP_MATERIAL SM
    ON SM.MATV_CODIGO = SE.IDEQUIPO
  LEFT JOIN USRPVU.SISACT_AP_TIPO_MATERIAL SATM
    ON SATM.TMATC_CODIGO = SM.TMATC_CODIGO
   AND SATM.PRDC_CODIGO = SM.PRDC_CODIGO
  LEFT JOIN USRPVU.SISACT_ITEM SI
    ON SI.ITEMN_CODIGO = SATM.TMATC_GRUPO
 WHERE PL.PLNC_TIPO_PRODUCTO = '05'
   --AND PL.PLNC_ESTADO = 1
   --AND CA.CAMPC_ESTADO = 1
   AND PS.ESTADO = 1
   AND CS.ESTADO = 1
   AND S.SERVC_ESTADO = 1
   AND G.GSRVC_ESTADO = 1
   AND AP.PAQTC_ESTADO = 1
   AND G.GSRVC_CODIGO NOT IN ('8', '15')
   AND S.SERVV_CODIGO NOT IN ('1806',
                              '1807',
                              '1808',
                              '3366',
                              '3367',
                              '3368',
                              '3369',
                              '3580',
                              '1589')
   AND (SE.ESTADO = 1 OR SE.ESTADO IS NULL)
   AND (SM.MATC_ESTADO = 1 OR SM.MATC_ESTADO IS NULL)
   AND (SM.PRDC_CODIGO = '05' OR SM.PRDC_CODIGO IS NULL)
   AND (SATM.TMATC_ESTADO = 1 OR SATM.TMATC_ESTADO IS NULL)
   AND (SI.ITEMC_ESTADO = 1 OR SI.ITEMC_ESTADO IS NULL)
   AND (SI.TIPIN_CODIGO = 8 OR SI.TIPIN_CODIGO IS NULL)
   AND CA.CAMPV_CODIGO NOT IN ('1614','1918','2209','1903','2051','1904','1036','2800','2738','2087','2401','3078','2984','2985','3024','2868','2860','1949')
   --AND CA.CAMPV_CODIGO IN (&Campv_Codigo)
   --AND PL.PLNV_CODIGO IN (&Plnv_Codigo)
   --AND CA.CAMPV_CODIGO||PL.PLNV_CODIGO IN (&Campv_Plnv)  

UNION ALL

SELECT CA.CAMPV_CODIGO AS CAMPANA,
       CA.CAMPV_DESCRIPCION AS DSC_CAMPANA,
       CA.MODALIDAD_VENTA AS MODALIDAD_CAMPANA,
       CA.CAMPV_FLUJO AS FLUJO_CAMPANA,
       CA.CAMPV_TIPO_OPERACION AS OPERACION_CAMPANA,
       CA.TOFC_CODIGO AS OFERTA_CAMPANA,      
       CA.CAMPD_FECHA_INICIO AS FEC_INI_CAMPANA,
       CA.CAMPD_FECHA_FIN AS FEC_FIN_CAMPANA,
       AP.PAQTV_CODIGO AS SOLUCION,
       AP.PAQTV_DESCRIPCION AS DSC_SOLUCION,
       PL.PLNV_CODIGO AS PLAN,
       PL.PLNV_DESCRIPCION AS DSC_PLAN,
       PL.PLNV_TIPO_FLUJO2 AS FLUJO_PLAN,
       PL.TPROC_CODIGO AS OFERTA_PLAN,      
       (SELECT LISTAGG(SAPO.TOPEN_CODIGO, '|') WITHIN GROUP(ORDER BY SAPO.TOPEN_CODIGO ASC)
          FROM USRPVU.SISACT_AP_PLAN_OPERACION SAPO
         WHERE SAPO.PLNV_CODIGO = PL.PLNV_CODIGO
           AND SAPO.PRDC_CODIGO = PL.PLNC_TIPO_PRODUCTO) AS OPERACION_PLAN,
       (SELECT LISTAGG(SAPD.DOCC_CODIGO, '|') WITHIN GROUP(ORDER BY SAPD.DOCC_CODIGO ASC)
          FROM USRPVU.SISACT_AP_PLAN_DOC SAPD
         WHERE SAPD.PLANC_CODIGO = PL.PLNV_CODIGO
           AND SAPD.PRDC_CODIGO = PL.PLNC_TIPO_PRODUCTO) AS DOCUMENTO_PLAN,
       (SELECT LISTAGG(SAPA.PLZAC_CODIGO, '|') WITHIN GROUP(ORDER BY SAPA.PLZAC_CODIGO ASC)
          FROM USRPVU.SISACT_AP_PLAN_ACUERDO SAPA
         WHERE SAPA.PLNV_CODIGO = PL.PLNV_CODIGO) AS PLAZO_PLAN,
       (SELECT LISTAGG(SAPB.PRCLN_CODIGO, '|') WITHIN GROUP(ORDER BY SAPB.PRCLN_CODIGO ASC)
          FROM USRPVU.SISACT_AP_PLAN_BILLETERA SAPB
         WHERE SAPB.PLNV_CODIGO = PL.PLNV_CODIGO
           AND SAPB.PRDC_CODIGO = PL.PLNC_TIPO_PRODUCTO) AS BILLETERA_PLAN,
       '' AS MAX_SECUENCIAL,
       '' AS SECUENCIAL,
       PL.PLNV_CODIGO_BSCS AS TMCODE,
       CS.SPCODE AS SPCODE,
       CS.SNCODE AS SNCODE,
       '' AS ACCION,
       '' AS DSC_PROMOCION,
       '' AS SPCODE_SHDES,
       '' AS DESCUENTO,
       '' AS PERIODO,
       '' AS TIPO_DESCUENTO,
       '' AS MOTIVO,
       '' AS FEC_INI_PROMOCION,
       '' AS FEC_FIN_PROMOCION,
       S.SERVV_CODIGO AS SERVICIO,
       S.SERVV_DESCRIPCION AS DSC_SERVICIO,
       PE.PRECIO_BASE AS CF_SIN_IGV,
       TO_CHAR(ROUND(PE.PRECIO_BASE * 1.18, 2), 'FM99990.00') AS CF_CON_IGV,
       '' AS BONO,
       '' AS IPTV,
       S.SERVV_CODIGO_EXT AS CODIGO_EXTERNO,
       S.SERVV_DES_EXT AS DSC_CODIGO_EXTERNO,
       S.SERVV_CAPACIDAD AS CAPACIDAD,
       S.SERVV_UNIDAD_CAPC AS UNIDAD,
       S.SERVI_CO_SER AS CO_SER,
       SE.IDEQUIPO AS EQUIPO,
       SE.EQUIPO AS DSC_EQUIPO,
       SE.CANT_EQUIPO AS CANT_EQUIPO,
       TO_CHAR(SM.MATV_ID_SAP) AS CODTIPEQU,
       SM.TIPEQU AS TIPEQU,
       SM.MATV_DES_SAP AS DSC_EQUIPO_SGA,
       TO_CHAR(SATM.TMATC_CODIGO) AS TIPO_EQUIPO,
       SATM.TMATV_DESCRIPCION AS DSC_TIPO_EQUIPO,
       SM.MATV_TIPO_MATERIAL AS CATEGORIA_EQUIPO,
       SI.ITEMN_DESCRIPCION AS DSC_GRUPO_EQUIPO,
       G.GSRVC_CODIGO AS GRUPO_SERVICIO,
       G.GSRVV_DESCRIPCION AS DSC_GRUPO_SERVICIO,
       G.GSRVC_PRINCIPAL AS GRUPO_PRINCIPAL,
       TO_CHAR(G.GSRVC_PADRE) AS GRUPO_PADRE,
       PS.PSRVV_SELECCIONABLE AS SELECCIONABLE,
       PS.PSRVC_FLG_DEFECTO AS DEFECTO,
       CASE
         WHEN G.GSRVC_PRINCIPAL = '1' THEN
          '1'
         WHEN PS.PSRVV_SELECCIONABLE = '1' AND PS.PSRVC_FLG_DEFECTO = '0' THEN
          '2'
         WHEN G.GSRVC_CODIGO NOT IN ('8', '15') AND
              PS.PSRVV_SELECCIONABLE = '0' AND PS.PSRVC_FLG_DEFECTO = '0' THEN
          '3'
         WHEN G.GSRVC_CODIGO IN ('8', '15') AND PS.PSRVV_SELECCIONABLE = '0' AND
              PS.PSRVC_FLG_DEFECTO = '0' THEN
          '4'
       END TIPO_SERVICIO,
       CASE
         WHEN G.GSRVC_PRINCIPAL = '1' THEN
          'CORE'
         WHEN PS.PSRVV_SELECCIONABLE = '1' AND PS.PSRVC_FLG_DEFECTO = '0' THEN
          'CORE ADICIONAL'
         WHEN G.GSRVC_CODIGO NOT IN ('8', '15') AND
              PS.PSRVV_SELECCIONABLE = '0' AND PS.PSRVC_FLG_DEFECTO = '0' THEN
          'ADICIONAL'
         WHEN G.GSRVC_CODIGO IN ('8', '15') AND PS.PSRVV_SELECCIONABLE = '0' AND
              PS.PSRVC_FLG_DEFECTO = '0' THEN
          'EQUIPO ALQUILER'
       END DSC_TIPO_SERVICIO,
       '' AS APLICA_FC,
       '' AS APLICA_PLAYA,
       '' AS FAMILIA
  FROM USRPVU.SISACT_AP_PLAN PL
  LEFT JOIN USRPVU.SISACT_AP_CAMPANA_PLAN CAC
    ON CAC.PLNV_CODIGO = PL.PLNV_CODIGO
   AND CAC.PRDC_CODIGO = PL.PLNC_TIPO_PRODUCTO
  LEFT JOIN USRPVU.SISACT_AP_CAMPANA CA
    ON CA.CAMPV_CODIGO = CAC.CAMPV_CODIGO
   AND CA.CAMPV_TIPO_PRODUCTO = CAC.PRDC_CODIGO
 INNER JOIN USRPVU.SISACT_AP_PLAN_SERV PS
    ON PS.PLNV_CODIGO = PL.PLNV_CODIGO
   AND PS.PRDC_CODIGO = PL.PLNC_TIPO_PRODUCTO
 INNER JOIN USRPVU.SISACT_CONFIG_SERVICIO CS
    ON CS.PLNV_CODIGO = PL.PLNV_CODIGO
   AND CS.PRDC_CODIGO = PL.PLNC_TIPO_PRODUCTO
   AND CS.TMCODE = PL.PLNV_CODIGO_BSCS
 INNER JOIN USRPVU.SISACT_AP_SERVICIO S
    ON S.SERVV_CODIGO = PS.SERVV_CODIGO
   AND S.SERVV_SPCODE = PS.SPCODE
   AND S.PRDC_CODIGO = PS.PRDC_CODIGO
   AND S.SERVV_CODIGO = CS.SERVV_CODIGO
   AND S.SERVV_ID_BSCS = CS.SNCODE
   AND S.SERVV_SPCODE = CS.SPCODE
   AND S.PRDC_CODIGO = CS.PRDC_CODIGO
 INNER JOIN USRPVU.SISACT_AP_GRUPO_SERVICIO G
    ON G.GSRVC_CODIGO = S.GSRVC_CODIGO
   AND G.PRDC_CODIGO = S.PRDC_CODIGO
 INNER JOIN USRPVU.SISACT_AP_PAQUETE_PLAN PP
    ON PP.PLNV_CODIGO = PL.PLNV_CODIGO
   AND PP.PRDC_CODIGO = PL.PLNC_TIPO_PRODUCTO
 INNER JOIN USRPVU.SISACT_AP_PAQUETE AP
    ON AP.PAQTV_CODIGO = PP.PAQTV_CODIGO
   AND AP.PRDC_CODIGO = PP.PRDC_CODIGO
 INNER JOIN USRPVU.SISACT_AP_PLAN_EQUIPO PE
    ON PE.PLNV_CODIGO = PL.PLNV_CODIGO
   AND PE.MATV_CODIGO = S.SERVV_CODIGO
   AND PE.PRDC_CODIGO = PL.PLNC_TIPO_PRODUCTO
  LEFT JOIN USRPVU.SISACT_AP_SERVICIO_EQUIPO SE
    ON SE.IDSERVICIO = S.SERVV_CODIGO
   AND SE.COD_GRUPO = S.GSRVC_CODIGO
  LEFT JOIN USRPVU.SISACT_AP_MATERIAL SM
    ON SM.MATV_CODIGO = SE.IDEQUIPO
  LEFT JOIN USRPVU.SISACT_AP_TIPO_MATERIAL SATM
    ON SATM.TMATC_CODIGO = SM.TMATC_CODIGO
   AND SATM.PRDC_CODIGO = SM.PRDC_CODIGO
  LEFT JOIN USRPVU.SISACT_ITEM SI
    ON SI.ITEMN_CODIGO = SATM.TMATC_GRUPO
 WHERE PL.PLNC_TIPO_PRODUCTO = '05'
   --AND PL.PLNC_ESTADO = 1
   --AND CA.CAMPC_ESTADO = 1
   AND PS.ESTADO = 1
   AND CS.ESTADO = 1
   AND S.SERVC_ESTADO = 1
   AND G.GSRVC_ESTADO = 1
   AND AP.PAQTC_ESTADO = 1
   AND S.SERVV_CODIGO NOT IN ('1806',
                              '1807',
                              '1808',
                              '3366',
                              '3367',
                              '3368',
                              '3369',
                              '3580',
                              '1589')
   AND (SE.ESTADO = 1 OR SE.ESTADO IS NULL)
   AND (SM.MATC_ESTADO = 1 OR SM.MATC_ESTADO IS NULL)
   AND (SM.PRDC_CODIGO = '05' OR SM.PRDC_CODIGO IS NULL)
   AND (PE.ESTADO = 1 OR PE.ESTADO IS NULL)
   AND (SATM.TMATC_ESTADO = 1 OR SATM.TMATC_ESTADO IS NULL)
   AND (SI.ITEMC_ESTADO = 1 OR SI.ITEMC_ESTADO IS NULL)
   AND (SI.TIPIN_CODIGO = 8 OR SI.TIPIN_CODIGO IS NULL)
   AND CA.CAMPV_CODIGO NOT IN ('1614','1918','2209','1903','2051','1904','1036','2800','2738','2087','2401','3078','2984','2985','3024','2868','2860','1949')
   --AND CA.CAMPV_CODIGO IN (&Campv_Codigo)
   --AND PL.PLNV_CODIGO IN (&Plnv_Codigo)  
   --AND CA.CAMPV_CODIGO||PL.PLNV_CODIGO IN (&Campv_Plnv)
 ORDER BY CAMPANA,
          DSC_CAMPANA,
          SOLUCION,
          PLAN,
          DSC_PLAN,
          SERVICIO,
          DSC_SERVICIO ASC) T
          WHERE
          1=1 AND
          CAMPANA = :codigo_campana
          --UPPER(T.DSC_CAMPANA) LIKE  ('%PUERTA%')
